import uuid
from datetime import datetime
from typing import Optional

from pydantic import BaseModel, EmailStr, Field, field_validator

from app.features.users.models import UserStatus


def check_admin_password(v: str) -> str:
    """Admin passwords: at least 10 characters, with a letter and a number."""
    if len(v) < 10 or not any(c.isalpha() for c in v) or not any(c.isdigit() for c in v):
        raise ValueError("Use at least 10 characters, with letters and numbers")
    return v


class AdminResponse(BaseModel):
    id: uuid.UUID
    email: str
    first_name: str
    last_name: str
    status: UserStatus
    is_super_admin: bool
    # True while the admin still has a temporary password (or was told to
    # pick a new one); temp_password_expires_at is set for a temporary one.
    must_change_password: bool
    temp_password_expires_at: Optional[datetime] = None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class AdminWithEmailStatus(AdminResponse):
    """After creating an admin or resetting a password: whether the email
    with the temporary password actually went out."""
    email_sent: bool


class PaginatedAdmins(BaseModel):
    items: list[AdminResponse]
    total: int
    limit: int
    offset: int


class AdminCreate(BaseModel):
    """The temporary password is generated by the server and emailed — the
    Super Admin never sees or sets it."""
    email: EmailStr
    first_name: str = Field(min_length=1, max_length=100)
    last_name: str = Field(default="", max_length=100)


class AdminUpdate(BaseModel):
    first_name: Optional[str] = Field(default=None, min_length=1, max_length=100)
    last_name: Optional[str] = Field(default=None, max_length=100)
    status: Optional[UserStatus] = None


class AuditEntry(BaseModel):
    id: uuid.UUID
    actor_email: str
    action: str
    target_email: Optional[str] = None
    details: Optional[str] = None
    created_at: datetime

    model_config = {"from_attributes": True}


class EmailUsage(BaseModel):
    sent_today: int
    blocked_today: int
    normal_cutoff: int
    daily_cap: int
    enabled: bool


class ResetCodeRequest(BaseModel):
    email: EmailStr


class ResetCodeConfirm(BaseModel):
    email: EmailStr
    code: str = Field(pattern=r"^\d{6}$")
    new_password: str

    @field_validator("new_password")
    @classmethod
    def _strong(cls, v: str) -> str:
        return check_admin_password(v)
